`timescale 1ns/1ps
//=============================================================================
// tb_hb_coef — 半带系数表本身的性质验收
//-----------------------------------------------------------------------------
// 这个 TB 不跑滤波器，只检查 lut/hb_odd.mem 这张表**作为一张半带表**是否成立。
// 为什么值得单独一个 TB：表是脚本生成的，脚本改坏了、文件被手改了一行、
// 或者生成器和 RTL 的抽头数对不上，fir 那侧的向量回放可能仍然"看起来正常"
// （因为向量也是同一张表生成的），必须有一条**只依赖定义**的断言。
//
// 检查的半带性质：
//   ① 长度 = K = (N-1)/2 = 30，没有 x（$readmemh 读不到时不报错，见已知坑 9）
//   ② 严格对称 o[i] == o[K-1-i]（线性相位 / 预加器省乘法器的前提）
//   ③ 奇数抽头和 = 16384 = 2^14，配合中心 16384 → 总系数和 32768 = 2^15
//   ④ A(0) = 1、A(0.25) = 0.5、A(0.5) = 0（半带的三个特征点）
//   ⑤ 幅度互补 A(f) + A(0.5-f) = 1（半带的定义性质）
//   ⑥ 阻带（0.3 / 0.4）确实被压到 -40 dB 以下
//   ⑦ hb5.mem（5 抽头教学小车）= [8192, 8192]
//=============================================================================
module tb_hb_coef;
    `include "tb_common.vh"

`ifndef HB_COEFDIR
  `define HB_COEFDIR "s04_resample/lut/"
`endif

    localparam integer CW = 16;
    localparam integer K  = 30;
    localparam integer M  = K;                 // 中心抽头下标 = 30

    reg signed [CW-1:0] coef [0:K-1];
    reg signed [CW-1:0] coef5 [0:1];

    integer i, z, sym_err, sum_odd;
    real amp, d;

    // ── 零相位幅度响应 A(f) = Σ h[k]·cos(2πf(k-M)) / 2^15 ──────────
    // 偶相只有中心抽头，所以只要把中心项加上、奇数抽头跑一遍循环即可。
    function real amp_at;
        input real f;
        integer ii;
        real acc;
        begin
            acc = 16384.0;
            for (ii = 0; ii < K; ii = ii + 1)
                acc = acc + coef[ii] * $cos(2.0 * 3.141592653589793 * f * (2*ii + 1 - M));
            amp_at = acc / 32768.0;
        end
    endfunction

    initial begin
        $readmemh({`HB_COEFDIR, "hb_odd.mem"}, coef);
        $readmemh({`HB_COEFDIR, "hb5.mem"}, coef5);

        // ── ① 读到了吗 ────────────────────────────────────────────
        z = 0;
        for (i = 0; i < K; i = i + 1)
            if ((^coef[i]) === 1'bx)
                z = z + 1;
        `check_eq("hb_odd.mem 的 30 个值全部读入（没有 x）", z, 0);
        `check_eq("hb_odd.mem 第一行 = 30（最外侧奇数抽头）", coef[0], 30);
        `check_eq("hb_odd.mem 最后一行 = 30（镜像，对称）", coef[K-1], 30);
        `check_eq("hb_odd.mem 中间一对 = 10387（最大奇数抽头）", coef[K/2-1], 10387);
        `check_eq("hb_odd.mem 中间一对的另一半也 = 10387", coef[K/2], 10387);

        // ── ② 对称 ────────────────────────────────────────────────
        sym_err = 0;
        for (i = 0; i < K/2; i = i + 1)
            if (coef[i] !== coef[K-1-i])
                sym_err = sym_err + 1;
        `check_eq("严格对称：o[i] == o[K-1-i] 对 15 对全成立", sym_err, 0);

        // ── ③ 系数和 ──────────────────────────────────────────────
        sum_odd = 0;
        for (i = 0; i < K; i = i + 1)
            sum_odd = sum_odd + coef[i];
        `check_eq("奇数抽头和 = 16384 = 2^14（配合中心 0.5 得到直流增益 1）",
                  sum_odd, 16384);
        `check_eq("总系数和 = 32768 = 2^15（1.0 的 Q1.15 表示）",
                  sum_odd + 16384, 32768);
        `check(coef[K/2-1] > 10000, "最大奇数抽头 > 10000（不是退化的表）");
        `check(coef[0] < coef[K/2-1], "外侧抽头比中心小（确实是低通）");

        // ── ④ 三个特征点 ──────────────────────────────────────────
        d = amp_at(0.0);
        `check(d > 0.999999 && d < 1.000001, "A(0) = 1（直流增益精确）");
        d = amp_at(0.25);
        `check(d > 0.499999 && d < 0.500001, "A(0.25) = 0.5（半带的 -6 dB 点）");
        d = amp_at(0.5);
        `check(d > -0.000001 && d < 0.000001, "A(0.5) = 0（奈奎斯特零点）");

        // ── ⑤ 幅度互补（半带的定义）───────────────────────────────
        z = 0;
        for (i = 0; i <= 20; i = i + 1) begin
            d = amp_at(0.0125 * i) + amp_at(0.5 - 0.0125 * i) - 1.0;
            if (d > 0.000001 || d < -0.000001)
                z = z + 1;
        end
        `check_eq("幅度互补 A(f)+A(0.5-f) = 1（21 个点，残差 < 1e-6）", z, 0);

        // ── ⑥ 通带 / 阻带 ─────────────────────────────────────────
        d = amp_at(0.10);
        `check(d > 0.99 && d < 1.01, "通带 A(0.10) 在 1 ± 1% 内");
        d = amp_at(0.30);
        `check(d > -0.01 && d < 0.01, "阻带 A(0.30) 已被压到 1% 以下（约 -40 dB）");
        d = amp_at(0.40);
        `check(d > -0.01 && d < 0.01, "阻带 A(0.40) 已被压到 1% 以下");

        // ── ⑦ 5 抽头教学小车 ─────────────────────────────────────
        `check_eq("hb5.mem[0] = 8192（= 0.25）", coef5[0], 8192);
        `check_eq("hb5.mem[1] = 8192（= 0.25，对称）", coef5[1], 8192);
        `check_eq("hb5 的奇数抽头和 = 16384（和主表同一约定）",
                  coef5[0] + coef5[1], 16384);

        tb_done;
    end

endmodule
