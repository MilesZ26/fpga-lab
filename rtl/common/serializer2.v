`timescale 1ns/1ps
//=============================================================================
// serializer2 — 2:1 并串转换（把一个 Fs 拍的两相，变成一个 2Fs 拍的串行流）
//-----------------------------------------------------------------------------
// 为什么要它：
//   s04 的 interp2 一次吐两个**并行**采样 (y_e, y_o)，对应 2Fs 上的相邻两点。
//   真正的 1 路 DAC 每个 2Fs 周期只能收一个点，所以必须把两相"并串"。
//   只把时钟提到 2 倍还不够 —— 仍然需要一个 2:1 mux。
//
// 时钟关系：
//   clk   = Fs，并行数据 d_e/d_o 在这个域里，每个 clk 更新一次；
//   clk2x = 2Fs，串行输出 d 在这个域里，每个 clk2x 输出一个点。
//   **clk2x 必须和 clk 同源、2 倍频、相位错开约 90°**（MMCM 的 CLKOUT0_PHASE）。
//
// 为什么不能只用一个自由跑的 ph 计数器（第一版就是这么写的，错了）
//-----------------------------------------------------------------------------
//   第一版：ph 在 clk2x 域里每个沿翻转，ph=0 选 d_e、ph=1 选 d_o。
//   仿真一跑就发现：复位释放的时刻决定了 ph 的起点，**偶相/奇相会整体互换**。
//   原因：ph 是 clk2x 域的计数器，它不知道 clk 域的"一帧"从哪里开始；
//   复位后它可能先数到 0，也可能先数到 1。频率完全正确，但两相拼反了。
//
//   正确做法：用 clk 的**上升沿**给 ph 定帧。在 clk2x 域里采样 clk，
//   检测到 clk 的上升沿（clk & ~clk_d）时：
//       · 锁存这一帧的 (d_e, d_o)；
//       · 当场输出 d_e（偶相）；
//   下一个 clk2x 沿输出 d_o（奇相）；再下一个 clk 上升沿重新定帧。
//   这样偶/奇相永远和 clk 域的数据帧对齐，复位先后不影响。
//
//   clk2x 的 90° 相位是为了让"clk 上升沿之后的第一个 clk2x 沿"清楚地出现；
//   如果两个时钟沿完全重合，clk 的采样会落在建立/保持窗口里（板上要避免）。
//
// 延迟：d_e/d_o 在 clk 上升沿后的第一个 clk2x 沿被锁存，d 在同一个沿输出 d_e；
//       下一个 clk2x 沿输出 d_o。对 clk 域看，串行流比并行帧晚约 0.5~1 拍。
//=============================================================================

module serializer2 #(
    parameter integer DW = 15          // 数据位宽
)(
    input  wire          clk,          // Fs：并行数据域
    input  wire          clk2x,        // 2Fs：串行输出域（同源、2 倍、相位错开）
    input  wire          rst_n,        // 异步复位，低有效
    input  wire [DW-1:0] d_e,          // 偶相 y[2n]
    input  wire [DW-1:0] d_o,          // 奇相 y[2n+1]
    output reg  [DW-1:0] d             // 串行流（每个 clk2x 一个样本）
);

    reg              clk_d;            // clk 在 clk2x 域的上一拍采样
    reg [DW-1:0]     e_r, o_r;         // 当前帧锁存的偶/奇相

    always @(posedge clk2x or negedge rst_n) begin
        if (!rst_n) begin
            clk_d <= 1'b0;
            e_r   <= {DW{1'b0}};
            o_r   <= {DW{1'b0}};
            d     <= {DW{1'b0}};
        end else begin
            clk_d <= clk;
            if (clk & ~clk_d) begin
                // clk 上升沿后的第一个 clk2x 沿：新的一帧，先出偶相
                e_r <= d_e;
                o_r <= d_o;
                d   <= d_e;
            end else begin
                // 同一帧的第二个 clk2x 沿：出奇相
                d   <= o_r;
            end
        end
    end

    // ── CDC 说明 ────────────────────────────────────────────────────
    // d_e/d_o 来自 clk 域，在 clk2x 域被锁存。clk2x = 2×clk 且同源、
    // 相位错开 90°，所以这是**同步多周期**路径，不是异步 CDC。
    // 综合/实现时在 XDC 里对 clk/clk2x 的路径加 set_max_delay 或
    // set_false_path，并注明"clk2x 是 clk 的 2 倍、相位错开"。
    // 不写约束也能跑（50 MHz 下路径很短），但时序报告会把它当跨时钟路径。

endmodule
