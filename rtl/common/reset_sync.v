//=============================================================================
// reset_sync — 异步复位、同步释放
//-----------------------------------------------------------------------------
// 功能：
//   把外部进来的异步复位（例如按键、上电复位）同步到 clk 时钟域，
//   使复位的"释放边沿"对齐到时钟，避免释放时各触发器退出复位的时刻不一致
//   而进入亚稳态。
//
// 时钟域：clk
// 延迟：  复位释放延迟 2 拍；复位拉低是异步的（立即生效）
// 复位值：sync 内部寄存器为 0
//
// 为什么需要它：
//   异步复位如果直接接到所有触发器，释放时刻若正好在时钟边沿附近，
//   有的触发器先退出复位、有的后退出，电路会进入不确定状态。
//   标准做法就是"异步置位、同步释放"。
//=============================================================================

`timescale 1ns/1ps

module reset_sync (
    input  wire clk,      // 目标时钟域
    input  wire arst_n,   // 异步复位输入，低有效
    output wire rst_n     // 同步释放后的复位输出，低有效
);

    (* ASYNC_REG = "TRUE" *) reg [1:0] sync; //这个寄存器是一个异步复位寄存器，最好保留成两个 FF 级联，避免不必要的优化

    always @(posedge clk or negedge arst_n) begin
        if (!arst_n)
            sync <= 2'b00;              // 异步复位：立即清零
        else
            sync <= {sync[0], 1'b1};    // 同步释放：先移入 1，两拍后输出变高
    end

    assign rst_n = sync[1]; // 输出信号是 sync 的高位，在arst_n变1后的第一个时钟沿还是0，第二个时钟沿变高

endmodule
